#!/usr/bin/env python3
"""Update local reading data from EDRDG. Requires Python stdlib; no runtime network.
Usage: python3 scripts/update_kanji_readings.py [--kanjidic CACHE.gz --jmdict CACHE.gz]
"""
import argparse, gzip, json, re, urllib.request, xml.etree.ElementTree as ET
from pathlib import Path
from datetime import datetime
from zoneinfo import ZoneInfo
ROOT=Path(__file__).resolve().parent.parent
p=argparse.ArgumentParser();p.add_argument('--kanjidic');p.add_argument('--jmdict');args=p.parse_args()
source=(ROOT/'kanji_data.js').read_text()
texts=set(re.findall(r"\btext:\s*['\"]([^'\"]+)['\"]",source))
chars=set(''.join(texts))
def get(path,url):
 if path:return Path(path).read_bytes()
 with urllib.request.urlopen(url,timeout=60) as r:return r.read()
def kana(s):return ''.join(chr(ord(c)-0x60) if '\u30a1'<=c<='\u30f6' else c for c in s)
singles={};words={}
raw=get(args.kanjidic,'https://www.edrdg.org/kanjidic/kanjidic2.xml.gz')
import io
for event,el in ET.iterparse(io.BytesIO(gzip.decompress(raw)),events=['end']):
 if el.tag!='character':continue
 char=el.findtext('literal')
 if char in chars:
  vals=set()
  for r in el.findall('./reading_meaning/rmgroup/reading'):
   if r.attrib.get('r_type') in ['ja_on','ja_kun']:
    reading=kana(r.text or '').strip('-');vals.add(reading.replace('.',''))
    if '.' in reading:vals.add(reading.split('.')[0])
  vals.update(kana(n.text or '') for n in el.findall('./reading_meaning/nanori'))
  singles[char]=sorted(v for v in vals if v)
 el.clear()
raw=get(args.jmdict,'https://www.edrdg.org/pub/Nihongo/JMdict_e.gz')
for event,el in ET.iterparse(io.BytesIO(gzip.decompress(raw)),events=['end']):
 if el.tag!='entry':continue
 spellings={k.text for k in el.findall('./k_ele/keb')} & texts
 for spelling in spellings:
  for reading in el.findall('r_ele'):
   restrictions={r.text for r in reading.findall('re_restr')}
   if reading.find('re_nokanji') is not None or (restrictions and spelling not in restrictions):continue
   word=reading.findtext('reb')
   if word:words.setdefault(spelling,set()).add(kana(word))
 el.clear()
words={k:sorted(v) for k,v in sorted(words.items())}
singles=dict(sorted(singles.items()))
header='// Derived from KANJIDIC2 and JMdict, (C) EDRDG and Jim Breen.\n// Reading data: CC BY-SA 4.0. See public/kanji-reading-sources.html.\n// Generated by scripts/update_kanji_readings.py; do not edit by hand.\n'
(ROOT/'kanji_readings_data.js').write_text(header+'export const SINGLE_KANJI_READINGS = '+json.dumps(singles,ensure_ascii=False,indent=2)+';\nexport const WORD_KANJI_READINGS = '+json.dumps(words,ensure_ascii=False,indent=2)+';\n')
(ROOT/'data/kanji-readings-source.json').write_text(json.dumps({'sources':['https://www.edrdg.org/kanjidic/kanjidic2.xml.gz','https://www.edrdg.org/pub/Nihongo/JMdict_e.gz'],'license':'CC BY-SA 4.0','copyright':'Electronic Dictionary Research and Development Group and Jim Breen','retrieved':str(datetime.now(ZoneInfo('Asia/Tokyo')).date()),'singleCharacters':len(singles),'words':len(words),'update':'python3 scripts/update_kanji_readings.py'},ensure_ascii=False,indent=2)+'\n')
print({'singleCharacters':len(singles),'words':len(words),'日':singles.get('日'),'文':singles.get('文')})
