import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../game.js',import.meta.url),'utf8');
const backing=new Map([['slot','old'],['other','unchanged']]);
let quota=true,blocked=false,removeBlocked=false;
const localStorage={getItem:k=>{if(blocked)throw Error('blocked');return backing.get(k)??null;},setItem(k,v){if(quota)throw Error('QuotaExceededError');backing.set(k,String(v));},removeItem(k){if(removeBlocked)throw Error('blocked');backing.delete(k);},get length(){if(blocked)throw Error('blocked');return backing.size;},key:i=>[...backing.keys()][i]??null};
const context=vm.createContext({localStorage});
vm.runInContext(source.slice(source.indexOf('const _fallbackMemStore'),source.indexOf('/* ==========================================================\n   ユーティリティ')),context);
assert.equal(context.storageGet('slot'),'old');
assert.equal(context.storageSet('slot','latest'),false);
assert.equal(context.storageGet('slot'),'latest','failed writes shadow older disk values');
context.storageSet('new','');assert.equal(context.storageGet('new'),'','empty strings are not missing values');
assert.equal(context.storageLen(),3);
assert.deepEqual(Array.from({length:context.storageLen()},(_,i)=>context.storageK(i)).sort(),['new','other','slot']);
removeBlocked=true;context.storageRemove('slot');assert.equal(context.storageGet('slot'),null);
assert.equal(context.storageLen(),2,'failed removal hides stale disk keys');
blocked=true;assert.equal(context.storageGet('new'),'');assert.equal(context.storageLen(),1);
blocked=false;quota=false;context.storageSet('slot','recovered');
assert.equal(context.storageGet('slot'),'recovered');assert.equal(backing.get('slot'),'recovered');
context.storageSet('new','durable');backing.set('new','another-tab');assert.equal(context.storageGet('new'),'another-tab','successful writes clear old memory shadow');
removeBlocked=false;context.storageRemove('new');assert.equal(context.storageGet('new'),null);
assert.equal(context.storageK(99),null);
const isolated=vm.createContext({});vm.runInContext(source.slice(source.indexOf('const _fallbackMemStore'),source.indexOf('/* ==========================================================\n   ユーティリティ')),isolated);
isolated.storageSet('a','value');assert.equal(isolated.storageGet('a'),'value');isolated.storageRemove('a');assert.equal(isolated.storageLen(),0);
console.log('PASS: quota errors read latest values, merged enumeration, deletion tombstones, blocked/absent storage and recovery. Memory fallback remains session-only.');
